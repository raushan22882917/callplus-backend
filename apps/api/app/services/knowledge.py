"""Knowledge base: chunk tenant documents and search them with Postgres
full-text search (no embedding provider required). The search_vector column
is generated by the database, so swapping in pgvector later only means adding
an embedding column and re-ranking here."""

import re
import uuid

from sqlalchemy import Text, delete, func, or_, select
from sqlalchemy.ext.asyncio import AsyncSession

from packages.database.models import KnowledgeChunk, KnowledgeDocument
from packages.database.models.guardrails import KnowledgeAIControl

CHUNK_TARGET_CHARS = 800
CHUNK_OVERLAP_CHARS = 100


def chunk_text(text: str) -> list[str]:
    """Split on paragraph boundaries into ~CHUNK_TARGET_CHARS pieces, hard-
    splitting any single paragraph that is longer, with a small overlap so a
    sentence cut at a boundary still appears whole in one chunk."""
    paragraphs = [p.strip() for p in re.split(r"\n\s*\n", text) if p.strip()]
    chunks: list[str] = []
    current = ""
    for paragraph in paragraphs:
        while len(paragraph) > CHUNK_TARGET_CHARS:
            if current:
                chunks.append(current)
                current = ""
            chunks.append(paragraph[:CHUNK_TARGET_CHARS])
            paragraph = paragraph[CHUNK_TARGET_CHARS - CHUNK_OVERLAP_CHARS :]
        if current and len(current) + len(paragraph) + 2 > CHUNK_TARGET_CHARS:
            chunks.append(current)
            current = paragraph
        else:
            current = f"{current}\n\n{paragraph}" if current else paragraph
    if current:
        chunks.append(current)
    return chunks


async def index_document(db: AsyncSession, document: KnowledgeDocument) -> None:
    await db.execute(delete(KnowledgeChunk).where(KnowledgeChunk.document_id == document.id))
    chunks = chunk_text(document.content)
    for index, content in enumerate(chunks):
        db.add(
            KnowledgeChunk(
                tenant_id=document.tenant_id,
                document_id=document.id,
                chunk_index=index,
                content=content,
            )
        )
    document.chunk_count = len(chunks)
    await db.flush()


async def search(
    db: AsyncSession, *, tenant_id: uuid.UUID, query: str, limit: int = 5
) -> list[dict]:
    if not query.strip():
        return []
    # Match ANY query term (OR) and let ts_rank_cd put chunks matching more
    # terms first: callers/LLMs phrase queries loosely ("refund window"), and
    # AND semantics would miss a chunk that only says "refund".
    ts_query = func.to_tsquery(
        "english",
        func.regexp_replace(
            func.cast(func.plainto_tsquery("english", query), Text), " & ", " | ", "g"
        ),
    )
    rank = func.ts_rank_cd(KnowledgeChunk.search_vector, ts_query)
    # Documents switched off for the AI (guardrails knowledge control) never surface.
    result = await db.execute(
        select(
            KnowledgeChunk,
            KnowledgeDocument.title,
            rank.label("rank"),
            KnowledgeAIControl.visibility,
        )
        .join(KnowledgeDocument, KnowledgeDocument.id == KnowledgeChunk.document_id)
        .outerjoin(KnowledgeAIControl, KnowledgeAIControl.document_id == KnowledgeChunk.document_id)
        .where(
            KnowledgeChunk.tenant_id == tenant_id,
            KnowledgeChunk.search_vector.op("@@")(ts_query),
            or_(KnowledgeAIControl.enabled.is_(None), KnowledgeAIControl.enabled.is_(True)),
        )
        .order_by(rank.desc())
        .limit(limit)
    )
    return [
        {
            "document_id": str(chunk.document_id),
            "title": title,
            "content": chunk.content,
            "score": float(score),
            "internal_only": visibility == "internal",
        }
        for chunk, title, score, visibility in result.all()
    ]
